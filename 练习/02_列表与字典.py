# ========== 1. 列表：一排有编号的格子 ==========
# 方括号 [ ] 装的，每一项用逗号隔开
fruits = ["苹果", "香蕉", "橘子", "葡萄"]

print("整个列表：", fruits)
print("第 0 个：", fruits[0])       # 苹果 —— 注意！编号从 0 数起，不是 1
print("第 2 个：", fruits[2])       # 橘子
print("倒数第 1 个：", fruits[-1])   # 葡萄 —— 负数 = 从后往前数
print("前两个：", fruits[0:2])      # ['苹果', '香蕉'] —— 切片，含头不含尾
print("一共几个：", len(fruits))     # 4 —— len() 数个数

print("-" * 40)

# ========== 2. 列表可以加、可以改、可以删 ==========
fruits.append("西瓜")        # 在末尾加一个
print("加了西瓜：", fruits)

fruits[0] = "青苹果"          # 把第 0 个改掉
print("改了第一个：", fruits)

fruits.remove("香蕉")         # 按内容删掉一个
print("删了香蕉：", fruits)

print("-" * 40)

# ========== 3. 字典：一叠贴了标签的抽屉 ==========
# 大括号 { } 装的，格式是「键: 值」
student = {
    "姓名": "qiao298",
    "天数": 4,
    "小时": 4.5,
}

print("整个字典：", student)
print("姓名是：", student["姓名"])     # 用「键」取值，不是用编号

student["天数"] = 5                  # 改一个已有的键
student["目标"] = "做 FDE"            # 加一个新的键
print("改 + 加之后：", student)

print("-" * 40)

# ========== 4. ★ 最重要的结构：列表套字典 ==========
# 外面是列表（有顺序），里面每一项是字典（有标签）
# 所有 API 返回的 JSON 都长这样 —— 这是 FDE 每天都要处理的东西
customers = [
    {"名字": "张三", "城市": "北京", "金额": 1200},
    {"名字": "李四", "城市": "上海", "金额": 800},
    {"名字": "王五", "城市": "北京", "金额": 2500},
]

print("客户名单：")
for c in customers:
    print(f"  {c['名字']}（{c['城市']}）消费 {c['金额']} 元")

print("-" * 40)

# ========== 5. 把数据算一遍 ==========
total = 0
for c in customers:
    total = total + c["金额"]
print(f"总消费：{total} 元")

print("北京客户：")
for c in customers:
    if c["城市"] == "北京":          # 两个等号 = 判断相等
        print(f"  → {c['名字']}")

best = customers[0]                  # 先假设第一个最高
for c in customers:
    if c["金额"] > best["金额"]:        # 遇到更高的就换掉
        best = c
print(f"消费最高：{best['名字']}（{best['金额']} 元）")

print("-" * 40)

